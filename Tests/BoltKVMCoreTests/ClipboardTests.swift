import XCTest
@testable import BoltKVMCore

final class ClipboardTests: XCTestCase {
    func testBundleRoundTripsTextAndBinary() throws {
        let text = Data("hello 剪切板".utf8)
        let image = Data((0..<4096).map { UInt8($0 & 0xff) })
        let bundle = ClipboardBundle(entries: [
            .init(uti: ClipboardSync.textType, data: text),
            .init(uti: ClipboardSync.pngType, data: image),
        ])
        let encoded = bundle.encode()
        XCTAssertEqual(encoded.count, bundle.encodedSize)
        let decoded = try XCTUnwrap(ClipboardBundle.decode(encoded))
        XCTAssertEqual(decoded.entries.count, 2)
        XCTAssertEqual(decoded.entries[0].uti, ClipboardSync.textType)
        XCTAssertEqual(decoded.entries[0].data, text)
        XCTAssertEqual(decoded.entries[1].data, image)
    }

    func testBundleRejectsTruncatedData() {
        let bundle = ClipboardBundle(entries: [.init(uti: ClipboardSync.textType, data: Data("x".utf8))])
        var encoded = bundle.encode()
        encoded.removeLast()
        XCTAssertNil(ClipboardBundle.decode(encoded))
    }

    func testManifestRejectsTraversalAndBadHash() {
        let good = String(repeating: "a", count: 64)
        let safe = FileManifest(items: [.init(name: "a.txt", isDirectory: false, size: 1, sha256: good)])
        XCTAssertTrue(FileManifest.isSafe(safe))

        let traversal = FileManifest(items: [.init(name: "../a.txt", isDirectory: false, size: 1, sha256: good)])
        XCTAssertFalse(FileManifest.isSafe(traversal))

        let absolute = FileManifest(items: [.init(name: "/tmp/a.txt", isDirectory: false, size: 1, sha256: good)])
        XCTAssertFalse(FileManifest.isSafe(absolute))

        let badHash = FileManifest(items: [.init(name: "a.txt", isDirectory: false, size: 1, sha256: "nope")])
        XCTAssertFalse(FileManifest.isSafe(badHash))

        let negative = FileManifest(items: [.init(name: "a.txt", isDirectory: false, size: -1, sha256: good)])
        XCTAssertFalse(FileManifest.isSafe(negative))
    }

    func testManifestHonoursConfiguredTransferCeiling() {
        let good = String(repeating: "c", count: 64)
        let manifest = FileManifest(items: [
            .init(name: "a.bin", isDirectory: false, size: 100, sha256: good),
        ])
        XCTAssertTrue(FileManifest.isSafe(manifest, maxTransferBytes: 100))
        XCTAssertFalse(FileManifest.isSafe(manifest, maxTransferBytes: 99))
    }

    func testManifestRejectsMoreThan64Items() {
        let good = String(repeating: "b", count: 64)
        let items = (0..<65).map {
            FileManifest.Item(name: "f\($0)", isDirectory: false, size: 1, sha256: good)
        }
        XCTAssertFalse(FileManifest.isSafe(FileManifest(items: items)))
    }

    func testHashIsStable() {
        XCTAssertEqual(ClipboardSync.hash(Data("abc".utf8)),
                       ClipboardSync.hash(Data("abc".utf8)))
        XCTAssertNotEqual(ClipboardSync.hash(Data("abc".utf8)),
                          ClipboardSync.hash(Data("abd".utf8)))
    }

    func testSymlinkDetection() throws {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: dir) }
        let plain = dir.appendingPathComponent("plain.txt")
        try Data("x".utf8).write(to: plain)
        XCTAssertFalse(ClipboardSync.containsSymlink(dir))
        let link = dir.appendingPathComponent("link")
        try FileManager.default.createSymbolicLink(at: link, withDestinationURL: URL(fileURLWithPath: "/etc"))
        XCTAssertTrue(ClipboardSync.containsSymlink(dir))
    }

    func testConcealedTypesAreListed() {
        XCTAssertTrue(ClipboardSync.concealedTypes.contains("org.nspasteboard.ConcealedType"))
        XCTAssertTrue(ClipboardSync.concealedTypes.contains("org.nspasteboard.TransientType"))
        XCTAssertTrue(ClipboardSync.concealedTypes.contains("org.nspasteboard.AutoGeneratedType"))
    }
}
