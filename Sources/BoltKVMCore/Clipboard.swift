import Foundation
import AppKit
import CryptoKit

/// Clipboard sync between the two ends of a session.
///
/// Four kinds of content ride the same authenticated connection:
///   - plain text (`public.utf8-plain-text`)
///   - rich text (`public.html`, `public.rtf`, plus the plain fallback)
///   - images (PNG; TIFF is converted before sending)
///   - files and folders (contents, not paths)
///
/// Everything is chunked: a packet is never larger than the 16 MB
/// `TCPConnection.maxPayload` guard, while a clipboard item may be much larger.
/// Text/rich text/images are reassembled in memory (a pasteboard item has to be
/// resident anyway); files stream to disk in `~/Downloads/BoltKVM Clipboard/`.
///
/// Echo prevention has two layers: `NSPasteboard.changeCount` stops us from
/// re-reading our own writes, and a SHA-256 of the encoded item stops the two
/// ends from bouncing identical content back and forth. Content marked
/// concealed/transient/auto-generated by password managers is never sent.
final class ClipboardSync: @unchecked Sendable {
    static let textType = "public.utf8-plain-text"
    static let htmlType = "public.html"
    static let rtfType = "public.rtf"
    static let pngType = "public.png"
    static let tiffType = "public.tiff"
    static let fileURLType = "public.file-url"
    static let concealedTypes = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    /// A pasteboard item can be large (a 6K PNG, a big HTML fragment), but it
    /// still has to be copied into the pasteboard on both ends. 512 MB is a
    /// safety valve rather than a link limit; `--clipboard-max-mb` can raise it.
    static let defaultMaxItemBytes = 512 << 20
    /// Chunk sizes. The non-file path keeps a small chunk so a clipboard item
    /// cannot delay a video frame for long; files use 1 MB to cut overhead.
    static let clipboardChunk = 256 << 10
    static let fileChunk = 1 << 20
    static let diskReserve: Int64 = 20 << 30

    private let conn: TCPConnection
    private let enabled: Bool
    private let maxItemBytes: Int
    /// 0 means "as much as fits on disk minus the reserve"; a positive value is
    /// an additional user-configured ceiling.
    private let maxTransferBytes: Int64
    private let queue = DispatchQueue(label: "boltkvm.clipboard", qos: .utility)
    private var timer: DispatchSourceTimer?
    private var lastChangeCount = -1
    private var lastSentHash = ""
    private var lastAppliedHash = ""
    private var nextTransferID: UInt32 = 1
    private var sending = false
    private var stopped = false

    private var incomingClipboard: (id: UInt32, total: Int, data: Data)?
    private var incomingFiles: IncomingFiles?

    var onSent: ((String) -> Void)?

    init(conn: TCPConnection, enabled: Bool,
         maxItemBytes: Int = ClipboardSync.defaultMaxItemBytes,
         maxTransferBytes: Int64 = 0) {
        self.conn = conn
        self.enabled = enabled
        self.maxItemBytes = max(1, maxItemBytes)
        self.maxTransferBytes = max(0, maxTransferBytes)
    }

    func start() {
        guard enabled else {
            log("clipboard: disabled")
            return
        }
        queue.async { [weak self] in
            guard let self, !self.stopped else { return }
            // Seed the count: whatever is on the pasteboard when the session
            // starts is old news, not something the user just copied.
            self.lastChangeCount = NSPasteboard.general.changeCount
            let t = DispatchSource.makeTimerSource(queue: self.queue)
            t.schedule(deadline: .now() + 0.4, repeating: 0.5)
            t.setEventHandler { [weak self] in self?.poll() }
            t.resume()
            self.timer = t
            log("clipboard: started (max item \(self.maxItemBytes >> 20) MB)")
        }
    }

    /// Stop polling and abort any partial file transfer. Safe to call more than
    /// once; waits for the queue so the connection can be closed afterwards.
    func stop() {
        queue.sync {
            guard !self.stopped else { return }
            self.stopped = true
            self.timer?.cancel()
            self.timer = nil
            self.incomingClipboard = nil
            self.incomingFiles?.abort()
            self.incomingFiles = nil
        }
    }

    // MARK: - Pasteboard polling

    private func poll() {
        guard !stopped, !sending else { return }
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        let types = (pb.types ?? []).map({ $0.rawValue })
        if types.contains(where: { Self.concealedTypes.contains($0) }) {
            log("clipboard: skipped concealed/transient item")
            return
        }

        // Finder copies carry both file URLs and an icon representation; files
        // win, otherwise every file copy would also send a picture of it.
        if types.contains(Self.fileURLType),
           let urls = pb.readObjects(forClasses: [NSURL.self],
                                     options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let inbox = Self.inboxURL().path
            if urls.contains(where: { $0.path == inbox || $0.path.hasPrefix(inbox + "/") }) {
                log("clipboard: skipped files already inside \(inbox)")
                return
            }
            sendFiles(urls)
            return
        }

        if let png = imageData(from: pb) {
            let entry = ClipboardBundle.Entry(uti: Self.pngType, data: png)
            sendBundle(ClipboardBundle(entries: [entry]), label: "image \(png.count) B")
            return
        }

        var entries: [ClipboardBundle.Entry] = []
        if let html = pb.data(forType: NSPasteboard.PasteboardType(Self.htmlType)) {
            entries.append(.init(uti: Self.htmlType, data: html))
        }
        if let rtf = pb.data(forType: NSPasteboard.PasteboardType(Self.rtfType)) {
            entries.append(.init(uti: Self.rtfType, data: rtf))
        }
        if let text = pb.string(forType: .string), !text.isEmpty {
            entries.append(.init(uti: Self.textType, data: Data(text.utf8)))
        }
        guard !entries.isEmpty else { return }
        sendBundle(ClipboardBundle(entries: entries), label: "\(entries.count) text representation(s)")
    }

    private func imageData(from pb: NSPasteboard) -> Data? {
        if let png = pb.data(forType: NSPasteboard.PasteboardType(Self.pngType)) {
            return png
        }
        guard let tiff = pb.data(forType: NSPasteboard.PasteboardType(Self.tiffType)),
              let rep = NSBitmapImageRep(data: tiff),
              let png = rep.representation(using: .png, properties: [:])
        else { return nil }
        return png
    }

    // MARK: - Sending clipboard bundles

    private func sendBundle(_ bundle: ClipboardBundle, label: String) {
        let data = bundle.encode()
        guard data.count <= maxItemBytes else {
            log("clipboard: skipped \(label); \(data.count) B exceeds the \(maxItemBytes >> 20) MB item limit")
            return
        }
        let hash = Self.hash(data)
        guard hash != lastSentHash, hash != lastAppliedHash else { return }
        lastSentHash = hash

        let id = nextTransferID
        nextTransferID &+= 1
        sending = true
        defer { sending = false }

        var offset = 0
        do {
            while offset < data.count {
                let end = min(offset + Self.clipboardChunk, data.count)
                var payload = Data(capacity: 12 + (end - offset))
                payload.appendUInt32BE(id)
                payload.appendUInt32BE(UInt32(data.count))
                payload.appendUInt32BE(UInt32(offset))
                payload.append(data.subdata(in: offset..<end))
                try conn.send(packet(type: .clipboard, payload: payload))
                offset = end
            }
            log("clipboard: sent \(label), \(data.count) B in \(max(1, (data.count + Self.clipboardChunk - 1) / Self.clipboardChunk)) chunk(s)")
            onSent?(label)
        } catch {
            log("clipboard: send failed: \(error)")
        }
    }

    func handleClipboard(_ payload: Data) {
        queue.async { [weak self] in
            self?.receiveClipboard(payload)
        }
    }

    private func receiveClipboard(_ payload: Data) {
        guard !stopped, payload.count >= 12 else { return }
        let id = payload.readUInt32BE(payload.startIndex)
        let total = Int(payload.readUInt32BE(payload.startIndex + 4))
        let offset = Int(payload.readUInt32BE(payload.startIndex + 8))
        guard total > 0, total <= maxItemBytes,
              offset >= 0, offset < total,
              payload.count - 12 <= total - offset else {
            log("clipboard: rejected malformed chunk (total \(total), offset \(offset))")
            return
        }
        let chunk = payload.subdata(in: (payload.startIndex + 12)..<payload.endIndex)
        if var current = incomingClipboard, current.id == id, current.data.count == offset {
            current.data.append(chunk)
            incomingClipboard = current
        } else if offset == 0 {
            incomingClipboard = (id, total, chunk)
        } else {
            log("clipboard: dropped out-of-order chunk")
            incomingClipboard = nil
            return
        }
        guard let current = incomingClipboard, current.data.count >= total else { return }
        incomingClipboard = nil
        guard current.data.count == total, let bundle = ClipboardBundle.decode(current.data) else {
            log("clipboard: could not decode incoming item")
            return
        }
        apply(bundle)
    }

    private func apply(_ bundle: ClipboardBundle) {
        let hash = Self.hash(bundle.encode())
        guard hash != lastAppliedHash else { return }
        let pb = NSPasteboard.general
        pb.clearContents()
        for entry in bundle.entries {
            if entry.uti == Self.textType {
                if let text = String(data: entry.data, encoding: .utf8) {
                    pb.setString(text, forType: .string)
                }
            } else {
                pb.setData(entry.data, forType: NSPasteboard.PasteboardType(entry.uti))
            }
        }
        lastChangeCount = pb.changeCount
        lastAppliedHash = hash
        lastSentHash = hash
        log("clipboard: applied \(bundle.entries.count) representation(s), \(bundle.encodedSize) B")
    }

    // MARK: - Sending files

    private func sendFiles(_ urls: [URL]) {
        var manifest = FileManifest(items: [])
        var sources: [URL] = []
        var temporary: [URL] = []
        defer { for url in temporary { try? FileManager.default.removeItem(at: url) } }

        for url in urls {
            var isDir: ObjCBool = false
            guard FileManager.default.fileExists(atPath: url.path, isDirectory: &isDir) else { continue }
            if isDir.boolValue {
                let zip = FileManager.default.temporaryDirectory
                    .appendingPathComponent("boltkvm-\(UUID().uuidString).zip")
                guard Self.zipDirectory(url, to: zip) else {
                    log("clipboard: could not zip \(url.lastPathComponent); skipped")
                    continue
                }
                temporary.append(zip)
                guard let size = Self.fileSize(zip), let hash = Self.fileHash(zip) else { continue }
                manifest.items.append(.init(name: url.lastPathComponent, isDirectory: true,
                                            size: size, sha256: hash))
                sources.append(zip)
            } else if (try? url.resourceValues(forKeys: [.isSymbolicLinkKey]).isSymbolicLink) == true {
                log("clipboard: skipped symlink \(url.lastPathComponent)")
            } else {
                guard let size = Self.fileSize(url), let hash = Self.fileHash(url) else { continue }
                manifest.items.append(.init(name: url.lastPathComponent, isDirectory: false,
                                            size: size, sha256: hash))
                sources.append(url)
            }
        }
        guard !manifest.items.isEmpty else { return }

        let total = manifest.items.reduce(Int64(0)) { $0 + $1.size }
        let diskLimit = Self.freeDiskBytes() - Self.diskReserve
        let limit = maxTransferBytes > 0 ? min(maxTransferBytes, diskLimit) : diskLimit
        guard total <= limit else {
            log("clipboard: refused \(total) B; transfer limit is \(limit) B")
            return
        }

        let id = nextTransferID
        nextTransferID &+= 1
        sending = true
        defer { sending = false }
        do {
            let json = try JSONEncoder().encode(manifest)
            var begin = Data(capacity: 5 + json.count)
            begin.append(FilePhase.begin.rawValue)
            begin.appendUInt32BE(id)
            begin.appendUInt32BE(UInt32(json.count))
            begin.append(json)
            try conn.send(packet(type: .fileTransfer, payload: begin))

            var sentBytes: Int64 = 0
            var nextProgress: Int64 = 64 << 20
            for (index, source) in sources.enumerated() {
                let item = manifest.items[index]
                guard let handle = try? FileHandle(forReadingFrom: source) else {
                    throw POSIXError(.EIO)
                }
                defer { try? handle.close() }
                while true {
                    guard let chunk = try handle.read(upToCount: Self.fileChunk), !chunk.isEmpty else { break }
                    var payload = Data(capacity: 7 + chunk.count)
                    payload.append(FilePhase.chunk.rawValue)
                    payload.appendUInt32BE(id)
                    payload.appendUInt16BE(UInt16(index))
                    payload.append(chunk)
                    try conn.send(packet(type: .fileTransfer, payload: payload))
                    sentBytes += Int64(chunk.count)
                    if sentBytes >= nextProgress {
                        log("clipboard: file progress \(sentBytes >> 20) / \(total >> 20) MB")
                        nextProgress += 64 << 20
                    }
                    // Leave room for the video frames behind us: a file chunk
                    // is 1 MB, so one short yield per chunk is enough.
                    usleep(500)
                }
                log("clipboard: sent \(item.isDirectory ? "folder" : "file") \(item.name) (\(item.size) B)")
            }
            var end = Data()
            end.append(FilePhase.end.rawValue)
            end.appendUInt32BE(id)
            try conn.send(packet(type: .fileTransfer, payload: end))
            log("clipboard: file transfer complete, \(manifest.items.count) item(s), \(total) B")
            onSent?("\(manifest.items.count) file(s), \(total) B")
        } catch {
            log("clipboard: file send failed: \(error)")
            var abort = Data()
            abort.append(FilePhase.abort.rawValue)
            abort.appendUInt32BE(id)
            try? conn.send(packet(type: .fileTransfer, payload: abort))
        }
    }

    func handleFile(_ payload: Data) {
        queue.async { [weak self] in
            self?.receiveFile(payload)
        }
    }

    private func receiveFile(_ payload: Data) {
        guard !stopped, payload.count >= 5 else { return }
        let phase = payload[payload.startIndex]
        let id = payload.readUInt32BE(payload.startIndex + 1)
        switch phase {
        case FilePhase.begin.rawValue:
            guard payload.count >= 9 else { return }
            let length = Int(payload.readUInt32BE(payload.startIndex + 5))
            guard length > 0, payload.count >= 9 + length else { return }
            let json = payload.subdata(in: (payload.startIndex + 9)..<(payload.startIndex + 9 + length))
            guard let manifest = FileManifest.decode(json),
                  FileManifest.isSafe(manifest, maxTransferBytes: maxTransferBytes) else {
                log("clipboard: rejected unsafe file manifest")
                return
            }
            incomingFiles?.abort()
            incomingFiles = IncomingFiles(id: id, manifest: manifest)
            incomingFiles?.begin()
            log("clipboard: receiving \(manifest.items.count) item(s), \(manifest.totalBytes) B")
        case FilePhase.chunk.rawValue:
            guard payload.count >= 7, let incoming = incomingFiles, incoming.id == id else { return }
            let index = Int(payload.readUInt16BE(payload.startIndex + 5))
            let data = payload.subdata(in: (payload.startIndex + 7)..<payload.endIndex)
            incoming.append(index: index, data: data)
        case FilePhase.end.rawValue:
            guard let incoming = incomingFiles, incoming.id == id else { return }
            incomingFiles = nil
            if let urls = incoming.finish() {
                let pb = NSPasteboard.general
                pb.clearContents()
                _ = pb.writeObjects(urls as [NSURL])
                lastChangeCount = pb.changeCount
                log("clipboard: file transfer applied, \(urls.count) item(s) in \(incoming.destination.path)")
            } else {
                log("clipboard: file transfer failed verification; nothing pasted")
                incoming.abort()
            }
        case FilePhase.abort.rawValue:
            if incomingFiles?.id == id { incomingFiles?.abort() }
            incomingFiles = nil
            log("clipboard: peer aborted the file transfer")
        default:
            log("clipboard: unknown file phase \(phase)")
        }
    }

    // MARK: - Helpers

    static func hash(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }

    static func fileHash(_ url: URL) -> String? {
        guard let handle = try? FileHandle(forReadingFrom: url) else { return nil }
        defer { try? handle.close() }
        var hasher = SHA256()
        while true {
            guard let chunk = try? handle.read(upToCount: 1 << 20), !chunk.isEmpty else { break }
            hasher.update(data: chunk)
        }
        return hasher.finalize().map { String(format: "%02x", $0) }.joined()
    }

    static func fileSize(_ url: URL) -> Int64? {
        (try? url.resourceValues(forKeys: [.fileSizeKey]).fileSize).map(Int64.init)
    }

    /// Where received files/folders are placed. Tests override it with
    /// `BOLTKVM_CLIPBOARD_DIR` so they do not touch the real Downloads folder.
    static func inboxURL() -> URL {
        if let path = ProcessInfo.processInfo.environment["BOLTKVM_CLIPBOARD_DIR"], !path.isEmpty {
            return URL(fileURLWithPath: path, isDirectory: true)
        }
        let downloads = FileManager.default.urls(for: .downloadsDirectory, in: .userDomainMask).first
            ?? FileManager.default.homeDirectoryForCurrentUser
        return downloads.appendingPathComponent("BoltKVM Clipboard", isDirectory: true)
    }

    static func freeDiskBytes() -> Int64 {
        let url = URL(fileURLWithPath: NSHomeDirectory())
        let value = try? url.resourceValues(forKeys: [.volumeAvailableCapacityForImportantUsageKey])
        return value?.volumeAvailableCapacityForImportantUsage ?? 0
    }

    static func zipDirectory(_ directory: URL, to zip: URL) -> Bool {
        let p = Process()
        p.executableURL = URL(fileURLWithPath: "/usr/bin/ditto")
        p.arguments = ["-c", "-k", "--sequesterRsrc", directory.path, zip.path]
        do { try p.run(); p.waitUntilExit(); return p.terminationStatus == 0 }
        catch { return false }
    }

    static func unzip(_ zip: URL, to directory: URL) -> Bool {
        let p = Process()
        p.executableURL = URL(fileURLWithPath: "/usr/bin/ditto")
        p.arguments = ["-x", "-k", zip.path, directory.path]
        do { try p.run(); p.waitUntilExit(); return p.terminationStatus == 0 }
        catch { return false }
    }

    /// Reject absolute paths and `..` before extracting a peer-supplied zip.
    static func zipEntriesAreSafe(_ zip: URL) -> Bool {
        let p = Process()
        p.executableURL = URL(fileURLWithPath: "/usr/bin/unzip")
        p.arguments = ["-Z1", zip.path]
        let pipe = Pipe()
        p.standardOutput = pipe
        do { try p.run() } catch { return false }
        let data = pipe.fileHandleForReading.readDataToEndOfFile()
        p.waitUntilExit()
        guard p.terminationStatus == 0 else { return false }
        let text = String(data: data, encoding: .utf8) ?? ""
        for line in text.split(separator: "\n") {
            let entry = String(line)
            if entry.hasPrefix("/") || entry.split(separator: "/").contains("..") { return false }
        }
        return true
    }
}

// MARK: - Wire structures

enum FilePhase: UInt8 {
    case begin = 1
    case chunk = 2
    case end = 3
    case abort = 4
}

struct ClipboardBundle {
    struct Entry {
        let uti: String
        let data: Data
    }

    var entries: [Entry]

    var encodedSize: Int {
        2 + entries.reduce(0) { $0 + 2 + $1.uti.utf8.count + 4 + $1.data.count }
    }

    func encode() -> Data {
        var d = Data(capacity: encodedSize)
        d.append(1)  // version
        d.append(UInt8(clamping: entries.count))
        for entry in entries {
            let uti = Data(entry.uti.utf8)
            d.appendUInt16BE(UInt16(clamping: uti.count))
            d.append(uti)
            d.appendUInt32BE(UInt32(clamping: entry.data.count))
            d.append(entry.data)
        }
        return d
    }

    static func decode(_ data: Data) -> ClipboardBundle? {
        guard data.count >= 2, data[data.startIndex] == 1 else { return nil }
        let count = Int(data[data.startIndex + 1])
        var offset = data.startIndex + 2
        var entries: [Entry] = []
        for _ in 0..<count {
            guard offset + 2 <= data.endIndex else { return nil }
            let utiLen = Int(data.readUInt16BE(offset)); offset += 2
            guard utiLen > 0, offset + utiLen + 4 <= data.endIndex else { return nil }
            guard let uti = String(data: data.subdata(in: offset..<(offset + utiLen)), encoding: .utf8)
            else { return nil }
            offset += utiLen
            let len = Int(data.readUInt32BE(offset)); offset += 4
            guard offset + len <= data.endIndex else { return nil }
            entries.append(Entry(uti: uti, data: data.subdata(in: offset..<(offset + len))))
            offset += len
        }
        guard !entries.isEmpty else { return nil }
        return ClipboardBundle(entries: entries)
    }
}

struct FileManifest: Codable {
    struct Item: Codable {
        var name: String
        var isDirectory: Bool
        var size: Int64
        var sha256: String
    }

    var items: [Item]

    var totalBytes: Int64 { items.reduce(0) { $0 + $1.size } }

    func encode() throws -> Data { try JSONEncoder().encode(self) }

    static func decode(_ data: Data) -> FileManifest? {
        try? JSONDecoder().decode(FileManifest.self, from: data)
    }

    static func isSafe(_ manifest: FileManifest, maxTransferBytes: Int64 = 0) -> Bool {
        guard !manifest.items.isEmpty, manifest.items.count <= 64 else { return false }
        for item in manifest.items {
            if item.name.isEmpty || item.name == "." || item.name == ".." { return false }
            if item.name.contains("/") || item.name.contains("\0") { return false }
            if item.size < 0 || item.sha256.count != 64 { return false }
            if !item.sha256.allSatisfy({ $0.isHexDigit }) { return false }
        }
        let diskLimit = ClipboardSync.freeDiskBytes() - ClipboardSync.diskReserve
        let limit = maxTransferBytes > 0 ? min(maxTransferBytes, diskLimit) : diskLimit
        return manifest.totalBytes >= 0 && manifest.totalBytes <= limit
    }
}

// MARK: - Incoming files

private final class IncomingFiles {
    let id: UInt32
    let manifest: FileManifest
    let destination: URL
    private let staging: URL
    private var handles: [FileHandle?]
    private var written: [Int64]
    private var failed = false

    init(id: UInt32, manifest: FileManifest) {
        self.id = id
        self.manifest = manifest
        self.destination = ClipboardSync.inboxURL()
        self.staging = destination.appendingPathComponent(".incoming-\(UUID().uuidString)", isDirectory: true)
        self.handles = Array(repeating: nil, count: manifest.items.count)
        self.written = Array(repeating: 0, count: manifest.items.count)
    }

    func begin() {
        let fm = FileManager.default
        try? fm.createDirectory(at: destination, withIntermediateDirectories: true)
        try? fm.createDirectory(at: staging, withIntermediateDirectories: true)
        log("clipboard: staging \(staging.path) items=\(manifest.items.count)")
        for (index, item) in manifest.items.enumerated() {
            let name = item.isDirectory ? "\(item.name).zip" : item.name
            let url = staging.appendingPathComponent("\(index)-\(name)")
            guard fm.createFile(atPath: url.path, contents: nil),
                  let handle = try? FileHandle(forWritingTo: url) else {
                log("clipboard: cannot stage \(url.lastPathComponent)")
                failed = true
                return
            }
            handles[index] = handle
        }
    }

    func append(index: Int, data: Data) {
        guard !failed, index >= 0, index < handles.count, let handle = handles[index] else {
            log("clipboard: no staging handle for item \(index) (failed=\(failed), count=\(handles.count))")
            failed = true
            return
        }
        if written[index] == 0 { log("clipboard: first chunk item \(index) \(data.count) B") }
        do {
            try handle.write(contentsOf: data)
            written[index] += Int64(data.count)
        } catch {
            log("clipboard: write failed for item \(index): \(error)")
            failed = true
        }
    }

    func finish() -> [URL]? {
        guard !failed, written == manifest.items.map(\.size) else {
            log("clipboard: size mismatch (\(written) vs \(manifest.items.map(\.size)))")
            return nil
        }
        for handle in handles { try? handle?.close() }
        let fm = FileManager.default
        var result: [URL] = []
        for (index, item) in manifest.items.enumerated() {
            let name = item.isDirectory ? "\(item.name).zip" : item.name
            let part = staging.appendingPathComponent("\(index)-\(name)")
            guard ClipboardSync.fileHash(part) == item.sha256 else {
                log("clipboard: checksum mismatch for \(item.name)")
                return nil
            }
            if item.isDirectory {
                guard ClipboardSync.zipEntriesAreSafe(part) else {
                    log("clipboard: unsafe zip entries in \(item.name)")
                    return nil
                }
                let target = Self.unique(item.name, in: destination)
                let extract = staging.appendingPathComponent("extract-\(index)", isDirectory: true)
                try? fm.createDirectory(at: extract, withIntermediateDirectories: true)
                guard ClipboardSync.unzip(part, to: extract),
                      let children = try? fm.contentsOfDirectory(at: extract, includingPropertiesForKeys: nil),
                      !children.isEmpty else {
                    log("clipboard: could not extract \(item.name)")
                    return nil
                }
                // ditto without --keepParent puts the folder's contents at the
                // root of `extract`; move that directory to its final name.
                guard (try? fm.moveItem(at: extract, to: target)) != nil else {
                    log("clipboard: could not place folder \(item.name)")
                    return nil
                }
                result.append(target)
            } else {
                let target = Self.unique(item.name, in: destination)
                guard (try? fm.moveItem(at: part, to: target)) != nil else {
                    log("clipboard: could not place file \(item.name)")
                    return nil
                }
                result.append(target)
            }
        }
        try? fm.removeItem(at: staging)
        return result
    }

    func abort() {
        for handle in handles { try? handle?.close() }
        try? FileManager.default.removeItem(at: staging)
    }

    private static func unique(_ name: String, in directory: URL) -> URL {
        let fm = FileManager.default
        let base = (name as NSString).deletingPathExtension
        let ext = (name as NSString).pathExtension
        var candidate = directory.appendingPathComponent(name)
        var n = 2
        while fm.fileExists(atPath: candidate.path) {
            let next = ext.isEmpty ? "\(base) \(n)" : "\(base) \(n).\(ext)"
            candidate = directory.appendingPathComponent(next)
            n += 1
        }
        return candidate
    }
